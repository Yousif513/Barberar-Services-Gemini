// Copies the controlled RoPA (docs/privacy/ropa.md) into the console bundle as a string with its SHA-256, so /admin/ropa shows
// exactly the versioned document (X2). Run after editing the document: node scripts/build-ropa.mjs
// web_platform/tests/ropa-document.test.mjs fails when the two differ.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../docs/privacy/ropa.md", import.meta.url), "utf8").replace(/\r\n/g, "\n");
const sha = createHash("sha256").update(source).digest("hex");
writeFileSync(new URL("../web_platform/src/lib/ropa-document.ts", import.meta.url),
  `// Generated by scripts/build-ropa.mjs from docs/privacy/ropa.md (the controlled source). Do not edit by hand.\n` +
  `export const ROPA_SOURCE = "docs/privacy/ropa.md";\nexport const ROPA_SHA256 = "${sha}";\n` +
  `export const ROPA_MARKDOWN = ${JSON.stringify(source)};\n`);
console.log(`ropa-document.ts written (${sha.slice(0, 12)})`);
